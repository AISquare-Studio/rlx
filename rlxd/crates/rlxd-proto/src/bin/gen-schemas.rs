//! Writes `rlxd/schemas/v1/` from rlxd-proto's types, or checks it is up to date.
//!
//! ```text
//! cargo run -p rlxd-proto --bin gen-schemas             # write the schemas
//! cargo run -p rlxd-proto --bin gen-schemas -- --check  # exit 1 if they drifted
//! ```
//!
//! The directory holds generated schemas only: writing removes any `*.json` there that
//! is no longer generated, and `--check` counts one as drift.

use std::collections::BTreeSet;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use rlxd_proto::schemas::{self, SchemaFile};

const USAGE: &str = "usage: gen-schemas [--check] [--dir DIR]

Writes rlxd/schemas/v1/ from rlxd-proto's types. With --check, writes nothing
and exits 1 if the directory differs from what would be written.
";

fn main() -> ExitCode {
    let args = match Args::parse(std::env::args_os().skip(1)) {
        Ok(args) => args,
        Err(message) => {
            eprint!("gen-schemas: {message}\n\n{USAGE}");
            return ExitCode::from(2);
        }
    };
    if args.help {
        print!("{USAGE}");
        return ExitCode::SUCCESS;
    }
    let files = schemas::all();
    let result = if args.check {
        check(&args.dir, &files)
    } else {
        write(&args.dir, &files)
    };
    match result {
        Ok(code) => code,
        Err(error) => {
            eprintln!("gen-schemas: {}: {error}", args.dir.display());
            ExitCode::FAILURE
        }
    }
}

struct Args {
    check: bool,
    help: bool,
    dir: PathBuf,
}

impl Args {
    fn parse(mut args: impl Iterator<Item = std::ffi::OsString>) -> Result<Self, String> {
        let mut parsed = Self {
            check: false,
            help: false,
            dir: default_dir(),
        };
        while let Some(arg) = args.next() {
            match arg.to_str() {
                Some("--check") => parsed.check = true,
                Some("-h" | "--help") => parsed.help = true,
                Some("--dir") => {
                    parsed.dir = args.next().ok_or("--dir needs a directory")?.into();
                }
                _ => return Err(format!("unexpected argument {}", arg.to_string_lossy())),
            }
        }
        Ok(parsed)
    }
}

/// `rlxd/schemas/v1`, found from this crate's own directory (`rlxd/crates/rlxd-proto`).
fn default_dir() -> PathBuf {
    let crate_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    let workspace = crate_dir
        .parent()
        .and_then(Path::parent)
        .expect("rlxd-proto lives at rlxd/crates/rlxd-proto");
    workspace.join("schemas").join("v1")
}

/// The `*.json` files in `dir` that `files` does not name.
fn stale(dir: &Path, files: &[SchemaFile]) -> io::Result<BTreeSet<String>> {
    let generated: BTreeSet<&str> = files.iter().map(|file| file.name).collect();
    let mut found = BTreeSet::new();
    for entry in fs::read_dir(dir)? {
        let entry = entry?;
        let name = entry.file_name().to_string_lossy().into_owned();
        if entry.file_type()?.is_file()
            && name.ends_with(".json")
            && !generated.contains(name.as_str())
        {
            found.insert(name);
        }
    }
    Ok(found)
}

fn check(dir: &Path, files: &[SchemaFile]) -> io::Result<ExitCode> {
    let mut drift = Vec::new();
    for file in files {
        match fs::read(dir.join(file.name)) {
            Ok(bytes) if bytes == file.contents.as_bytes() => {}
            Ok(_) => drift.push(format!("{} differs from rlxd-proto", file.name)),
            Err(error) if error.kind() == io::ErrorKind::NotFound => {
                drift.push(format!("{} is missing", file.name));
            }
            Err(error) => return Err(error),
        }
    }
    for name in stale(dir, files)? {
        drift.push(format!("{name} is not generated by rlxd-proto"));
    }
    if drift.is_empty() {
        println!("gen-schemas: {} schemas up to date", files.len());
        return Ok(ExitCode::SUCCESS);
    }
    for line in &drift {
        eprintln!("gen-schemas: drift: {line}");
    }
    eprintln!(
        "gen-schemas: regenerate with `cargo run -p rlxd-proto --bin gen-schemas` and commit"
    );
    Ok(ExitCode::FAILURE)
}

fn write(dir: &Path, files: &[SchemaFile]) -> io::Result<ExitCode> {
    fs::create_dir_all(dir)?;
    for name in stale(dir, files)? {
        fs::remove_file(dir.join(&name))?;
        println!("gen-schemas: removed {name}");
    }
    for file in files {
        fs::write(dir.join(file.name), &file.contents)?;
    }
    println!("gen-schemas: wrote {} schemas", files.len());
    Ok(ExitCode::SUCCESS)
}
